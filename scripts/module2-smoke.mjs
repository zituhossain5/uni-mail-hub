import assert from 'node:assert/strict';
import { createHmac, randomBytes } from 'node:crypto';
import { PrismaClient } from '../packages/database/generated/client/index.js';

const web = process.env.WEB_URL;
const email = process.env.SEED_ADMIN_EMAIL;
const password = process.env.SEED_ADMIN_PASSWORD;
assert(web && email && password, 'WEB_URL and seed admin credentials are required');
const db = new PrismaClient();
async function json(path, { method = 'GET', body, cookie } = {}) {
  const response = await fetch(`${web}/api/v1/${path}`, { method, headers: { Origin: web, ...(cookie ? { Cookie: cookie } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  return { status: response.status, data: await response.json() };
}
let cookie; let projectId; let domainId; let mailboxId; let serverId; let memberId;
const suffix = Date.now().toString(36);
const secret = randomBytes(24).toString('hex');
try {
  assert.equal((await json('mail-servers')).status, 401);
  const member = await db.user.create({ data: { name: 'Smoke member', email: `member-${suffix}@example.com`, passwordHash: 'not-used', role: 'MEMBER' } });
  memberId = member.id;
  const header = Buffer.from(JSON.stringify({ alg: 'HS256', typ: 'JWT' })).toString('base64url');
  const payload = Buffer.from(JSON.stringify({ sub: member.id, exp: Math.floor(Date.now() / 1000) + 300 })).toString('base64url');
  const signature = createHmac('sha256', process.env.JWT_SECRET).update(`${header}.${payload}`).digest('base64url');
  const memberCookie = `umh_session=${header}.${payload}.${signature}`;
  assert.equal((await json('mail-servers', { cookie: memberCookie })).status, 403);
  const login = await json('auth/login', { method: 'POST', body: { email, password } });
  assert.equal(login.status, 200);
  const loginResponse = await fetch(`${web}/api/v1/auth/login`, { method: 'POST', headers: { Origin: web, 'Content-Type': 'application/json' }, body: JSON.stringify({ email, password }) });
  cookie = loginResponse.headers.get('set-cookie')?.split(';')[0];
  assert(cookie);
  const server = await json('mail-servers', { method: 'POST', cookie, body: { name: 'Mailpit smoke', providerType: 'GENERIC', imapHost: null, imapPort: null, imapSecurity: 'TLS', smtpHost: '127.0.0.1', smtpPort: 51025, smtpSecurity: 'NONE', smtpAuthMode: 'NONE' } });
  assert.equal(server.status, 201, JSON.stringify(server.data)); serverId = server.data.id;
  assert.equal((await json('mail-servers', { cookie })).data.some(item => item.id === serverId), true);
  const badPort = await json('mail-servers', { method: 'POST', cookie, body: { ...server.data, name: 'Bad', smtpPort: 0 } });
  assert.equal(badPort.status, 400);
  const project = await json('projects', { method: 'POST', cookie, body: { name: 'Connectivity smoke', slug: `connect-${suffix}` } });
  assert.equal(project.status, 201); projectId = project.data.id;
  const domain = await json('domains', { method: 'POST', cookie, body: { projectId, domain: `connect-${suffix}.example.com` } });
  assert.equal(domain.status, 201); domainId = domain.data.id;
  const mailbox = await json('mailboxes', { method: 'POST', cookie, body: { projectId, domainId, mailServerId: serverId, email: `test@connect-${suffix}.example.com` } });
  assert.equal(mailbox.status, 201, JSON.stringify(mailbox.data)); mailboxId = mailbox.data.id;
  assert.equal((await json(`mailboxes/${mailboxId}/credentials`, { method: 'PUT', cookie: memberCookie, body: { username: mailbox.data.email, password: secret } })).status, 403);
  const page = await fetch(`${web}/mailboxes/${mailboxId}`, { headers: { Cookie: cookie } });
  assert.equal(page.status, 200);
  assert.equal((await json(`mail-servers/${serverId}`, { method: 'DELETE', cookie })).data.code, 'MAIL_SERVER_IN_USE');
  const initial = await json(`mailboxes/${mailboxId}/credentials/status`, { cookie });
  assert.equal(initial.data.configured, false);
  const saved = await json(`mailboxes/${mailboxId}/credentials`, { method: 'PUT', cookie, body: { username: mailbox.data.email, password: secret } });
  assert.equal(saved.status, 200, JSON.stringify(saved.data));
  assert.equal(saved.data.configured, true);
  assert.equal(JSON.stringify(saved.data).includes(secret), false);
  assert.equal(JSON.stringify(saved.data).includes('encryptedPassword'), false);
  const stored = await db.mailboxCredential.findUnique({ where: { mailboxId } });
  assert(stored && stored.encryptedPassword !== secret);
  assert.equal(JSON.stringify(stored).includes(secret), false);
  const read = await json(`mailboxes/${mailboxId}`, { cookie });
  assert.equal(JSON.stringify(read.data).includes(secret), false);
  assert.equal(JSON.stringify(read.data).includes('encryptedPassword'), false);
  const smtp = await json(`mailboxes/${mailboxId}/test-smtp`, { method: 'POST', cookie });
  assert.equal(smtp.data.smtp.status, 'SUCCESS', JSON.stringify(smtp.data));
  const combined = await json(`mailboxes/${mailboxId}/test-connection`, { method: 'POST', cookie });
  assert.equal(combined.data.imap.errorCode, 'MAIL_SERVER_NOT_CONFIGURED');
  assert.equal(combined.data.smtp.status, 'SUCCESS');
  const history = await json(`mailboxes/${mailboxId}/connection-checks`, { cookie });
  assert(history.data.length >= 3);
  assert.equal((await json(`mailboxes/${mailboxId}`, { cookie })).data.status, 'WARNING');
  const serverPatch = await json(`mail-servers/${serverId}`, { method: 'PATCH', cookie, body: { imapHost: '127.0.0.1', imapPort: 59993, imapSecurity: 'NONE' } });
  assert.equal(serverPatch.status, 200);
  const imapFailure = await json(`mailboxes/${mailboxId}/test-imap`, { method: 'POST', cookie });
  assert.equal(imapFailure.data.imap.errorCode, 'IMAP_CONNECTION_REFUSED', JSON.stringify(imapFailure.data));
  assert.equal(JSON.stringify(imapFailure.data).includes(secret), false);
  const rotatedSecret = randomBytes(24).toString('hex');
  const replaced = await json(`mailboxes/${mailboxId}/credentials`, { method: 'PUT', cookie, body: { username: mailbox.data.email, password: rotatedSecret } });
  assert.equal(replaced.status, 200);
  assert.equal(JSON.stringify(replaced.data).includes(rotatedSecret), false);
  assert.notEqual((await db.mailboxCredential.findUnique({ where: { mailboxId } })).encryptedPassword, stored.encryptedPassword);
  assert.equal((await json(`mailboxes/${mailboxId}`, { cookie })).data.status, 'UNKNOWN');
  const removed = await json(`mailboxes/${mailboxId}/credentials`, { method: 'DELETE', cookie });
  assert.equal(removed.data.configured, false);
  assert.equal((await json(`mailboxes/${mailboxId}/credentials/status`, { cookie })).data.configured, false);
  const audits = await db.auditLog.findMany({ where: { entityId: mailboxId } });
  assert(audits.some(event => event.action === 'MAILBOX_CREDENTIAL_REPLACED'));
  assert.equal(JSON.stringify(audits).includes(secret) || JSON.stringify(audits).includes(rotatedSecret), false);
  assert.equal((await fetch(`${web}/mail-servers`, { headers: { Cookie: cookie } })).status, 200);
  assert.equal((await fetch(`${web}/mail-servers/${serverId}`, { headers: { Cookie: cookie } })).status, 200);
  assert.equal((await json(`mail-servers/${serverId}`, { method: 'PATCH', cookie, body: { status: 'DISABLED' } })).status, 200);
  assert.equal((await json(`mailboxes/${mailboxId}`, { method: 'PATCH', cookie, body: { displayName: 'Still editable' } })).status, 200);
  assert.equal((await json(`mailboxes/${mailboxId}`, { method: 'PATCH', cookie, body: { mailServerId: null } })).status, 200);
  assert.equal((await json(`mail-servers/${serverId}`, { method: 'DELETE', cookie })).status, 200);
  serverId = undefined;
  console.log('Module 2 smoke passed: protected CRUD, encrypted credential lifecycle, Mailpit SMTP, independent IMAP failure, history, health, audit, pages.');
} finally {
  if (cookie) {
    if (mailboxId) await json(`mailboxes/${mailboxId}`, { method: 'DELETE', cookie });
    if (domainId) await json(`domains/${domainId}`, { method: 'DELETE', cookie });
    if (projectId) await json(`projects/${projectId}`, { method: 'DELETE', cookie });
    if (serverId) await json(`mail-servers/${serverId}`, { method: 'DELETE', cookie });
  }
  if (memberId) await db.user.delete({ where: { id: memberId } });
  await db.$disconnect();
}
